#!/usr/bin/env python3
"""
mcp_lab_server: a config-driven MCP server for learning how MCP servers work.

You do not edit this file. You edit a TOML config that declares the server's identity, its tools,
its prompts and its resources, then restart the server. That is the whole point: an MCP server is
mostly a *manifest* plus a little behaviour, and the manifest is what the model actually reads.

    ./mcp_lab_server.py --config examples/looney-tunes-compliance.toml --validate
    ./mcp_lab_server.py --config my-server.toml                       # stdio (for opencode)
    ./mcp_lab_server.py --config my-server.toml --http 0.0.0.0:1491   # HTTP (for curl)

Stdlib only. No dependencies, no build. Python 3.11+ (for tomllib).
"""
